param(
  [string]$Source = (Join-Path $PSScriptRoot '..\data\products.json'),
  [string]$Dest = (Join-Path $PSScriptRoot '..\..\assets\live.js'),
  [string]$ShareDir = (Join-Path $PSScriptRoot '..\..\pages\p')
)
# Wraps the bot output (data\products.json) into site\assets\live.js so the website can read it.
# The site merges these items next to the hand-picked ones in data.js (see site\assets\site.js).
$ErrorActionPreference = 'Stop'

if (-not (Test-Path -LiteralPath $Source)) {
  Write-Host "[X] $Source not found. Run 3_run_bot.bat first."
  exit 1
}
$raw = [IO.File]::ReadAllText($Source, [Text.Encoding]::UTF8).Trim()
try { $json = $raw | ConvertFrom-Json } catch {
  Write-Host "[X] $Source is not valid JSON - live.js was NOT changed."
  exit 1
}
if ($null -eq $json.products) {
  Write-Host "[X] $Source has no 'products' list - live.js was NOT changed."
  exit 1
}
$count = @($json.products).Count

$out = [IO.Path]::GetFullPath($Dest)

# Backup the current live.js before overwriting (keep newest 30) -> bot\_backups
if (Test-Path -LiteralPath $out) {
  $bk = Join-Path (Split-Path $PSScriptRoot -Parent) '_backups'
  New-Item -ItemType Directory -Force -Path $bk | Out-Null
  Copy-Item -LiteralPath $out -Destination (Join-Path $bk ('live_' + (Get-Date -Format 'yyyyMMdd_HHmmss') + '.js'))
  Get-ChildItem $bk -Filter 'live_*.js' | Sort-Object Name -Descending | Select-Object -Skip 30 | Remove-Item -Force
}
# Public file: drop fields the site never reads (commission rates are private) and the indentation (about 20% smaller).
$raw = [regex]::Replace($raw, '(?m)^[ \t]*"(commission_pct|save_pct)":[^\r\n]*,\r?\n', '')
$raw = [regex]::Replace($raw, '(?m)^[ \t]+', '')
$js = "/* generated by bot\publish_to_site.ps1 - do not edit by hand */`r`nwindow.LIVE = $raw;`r`n"
[IO.File]::WriteAllText($out, $js, (New-Object Text.UTF8Encoding($false)))

Write-Host "[OK] $count products -> $out (updated_at: $($json.updated_at))"
# Static pages for Google/Facebook (no JavaScript needed to read them) - built by build_static_pages.js from the
# public files just written (live.js, data.js, options.js):
#   pages\p\<key>.html (one per product, from share_template.html, keeps the og: preview), pages\m\*.html (per model
#   and model x style), sitemap.xml + robots.txt at the site root. ($ShareDir is no longer used; kept for old callers.)
# If node is missing or the builder fails, the existing static pages are left as they are.
$builder = Join-Path $PSScriptRoot 'build_static_pages.js'
$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) {
  Write-Host "[!] node not found - static pages / sitemap NOT rebuilt (install Node.js, then run 6_publish_to_site.bat)"
} elseif (Test-Path -LiteralPath $builder) {
  $ErrorActionPreference = 'Continue'
  & $node.Source $builder
  if ($LASTEXITCODE -ne 0) { Write-Host "[!] build_static_pages.js failed (exit $LASTEXITCODE) - live.js is updated, static pages kept as before" }
  $ErrorActionPreference = 'Stop'
}
if ($count -eq 0) {
  Write-Host "[!] 0 products. If publish_only_with_affiliate_link is true in config.json, add links to affiliate_links.csv."
}
exit 0
