# -*- coding: utf-8 -*-
"""บอทดึง "ตัวเลือกสินค้า" จากหน้าสินค้า Shopee — รุ่นมือถือที่ร้านมีจริง + ตัวเลือกสี (พร้อมรูปตัวเลือก) + ของหมด
ทำไม: เว็บเดิมเดารุ่นจากชื่อสินค้า (ชื่อไม่ระบุรุ่น เช่น Wishwindy = ไม่ขึ้นหน้าลองทาบเลย · ชื่อ "11–17" = เดาเกินจริง)
     ตัวเลือกในหน้าร้านคือข้อมูลที่ถูกต้องที่สุด → เว็บใช้เป็น "✓ ยืนยันรุ่นแล้ว" แทนการเดา

วิธีทำงาน: เปิดหน้าสินค้าใน Chrome ของบอท (ล็อกอินเดิม) แล้ว "ฟัง" ข้อมูลที่หน้าเว็บโหลดเอง (ไม่ยิง API ตรง)
          ใช้ Bot.goto เดิมทุกอย่าง: เว้น 25–45 วิ/หน้า · พักยาวทุก 8 หน้า · เจอ verify ให้คนกดเองในหน้าต่าง Chrome · guard lock
ใช้:   ผู้ใช้รันผ่าน 2_run/10_collect_images.bat (ขั้นที่ 2 ต่อจากเก็บรูปอุปกรณ์เสริม) หรือ
       python scripts/fetch_options.py                  คิวอัตโนมัติ 8 ชิ้น (เคสที่ลองทาบได้ → ชื่อไม่ระบุรุ่น → ขายดี)
       python scripts/fetch_options.py 1382380664_24047313901 ...   เฉพาะชิ้นที่ระบุ (รหัส ร้าน_สินค้า หรือลิงก์เต็ม)
       --limit 8  --days 14 (ข้อมูลเก่ากว่านี้ดึงใหม่)  --dry (ดูคิวเฉยๆ ไม่เปิด Shopee)  --force (หลังยืนยันเองแล้ว)
ผล:   data/options.json  {key: {phone: [ชื่อตัวเลือกรุ่นที่ซื้อได้], off: [รุ่นที่หมด], colors: [{n, img}], tiers, checked_at}}
      บันทึกทีละชิ้น (โดนบล็อกกลางทางก็ไม่เสียของที่ได้แล้ว) · เขียน assets/options.js ให้เว็บเองตอนจบรอบ (ไม่ต้องรัน 6_publish)"""
import argparse, json, os, re, sys, time
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "bot"))
import bot as B
import guard

WHO = "fetch_options"
OUT = ROOT / "bot" / "data" / "options.json"
PRODUCTS = ROOT / "bot" / "data" / "products.json"
TRYON = ROOT / "assets" / "tryon.js"
FMT = "%Y-%m-%d %H:%M:%S"
KEY_RE = re.compile(r"(\d{4,})_(\d{6,})")
# กลุ่มตัวเลือกที่เป็นรุ่นมือถือ (เหมือน bot.variant_info) + คำบอกรุ่นที่ร้านไทยใช้บ่อย
PHONE_RE = re.compile(B.PHONE_OPT_RE.pattern + r"|pro\s*max|promax|\bplus\b|ultra|รุ่น", re.I)
COLOR_HINT_RE = re.compile(r"สี|ลาย|แบบ|colou?r|style|pattern|design", re.I)


def log(*x):
    print(time.strftime("%H:%M:%S"), *x, flush=True)


def load(path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return default


def save(opts):
    tmp = OUT.with_suffix(".tmp")
    tmp.write_text(json.dumps(opts, ensure_ascii=False, indent=1), encoding="utf-8")
    os.replace(tmp, OUT)   # เขียนทับแบบไม่ขาดกลางทาง


SITE_JS = ROOT / "assets" / "options.js"


def write_site_js(opts):
    """assets/options.js ให้หน้าเว็บอ่าน (site.js แปลงชื่อตัวเลือกเป็นรุ่นด้วย optSlugs) — เฉพาะชิ้นที่มีตัวเลือกรุ่นซื้อได้"""
    pub = {k: {"p": v["phone"], "t": v.get("checked_at", "")[:10]} for k, v in sorted(opts.items())
           if not v.get("error") and v.get("phone")}
    js = ("/* generated by bot/scripts/fetch_options.py - do not edit by hand */\r\nwindow.OPTS = "
          + json.dumps(pub, ensure_ascii=False, separators=(",", ":")) + ";\r\n")
    tmp = SITE_JS.with_suffix(".tmp")
    tmp.write_text(js, encoding="utf-8")
    os.replace(tmp, SITE_JS)
    return len(pub)


def phone_tier(tiers):
    """index ของกลุ่มตัวเลือกที่ชื่อตัวเลือกดูเป็นรุ่นมือถือมากที่สุด (≥ ครึ่ง) หรือ None"""
    best, bi = 0.0, None
    for i, t in enumerate(tiers):
        o = t["options"]
        if o:
            r = sum(1 for x in o if PHONE_RE.search(x)) / len(o)
            if r > best:
                best, bi = r, i
    return bi if best >= 0.5 else None


def extract(data, iid):
    """หา dict สินค้าในข้อมูลที่หน้าโหลด (มี itemid ตรง + tier_variations) แล้วย่อเหลือเฉพาะตัวเลือก"""
    for d in B.walk(data):
        if str(d.get("itemid") or d.get("item_id") or "") != iid or not isinstance(d.get("tier_variations"), list):
            continue
        tiers = []
        for t in d["tier_variations"]:
            if not isinstance(t, dict):
                continue
            opts = [str(o).strip() for o in (t.get("options") or [])]
            imgs = [str(x or "") for x in (t.get("images") or [])]
            tiers.append({"name": str(t.get("name") or "").strip(), "options": opts,
                          "images": (imgs + [""] * len(opts))[:len(opts)]})
        # ตัวเลือกย่อย (models): ใช้ดูว่ารุ่นไหนซื้อได้จริง (status 1 และมีของ)
        ok_idx = {}
        for m in d.get("models") or []:
            if not isinstance(m, dict):
                continue
            idx = (m.get("extinfo") or {}).get("tier_index") or []
            stock = m.get("normal_stock", m.get("stock"))
            live = m.get("status", 1) == 1 and (stock is None or stock > 0) and (B.money(m.get("price")) or 0) > 0
            for t, i in enumerate(idx):
                if isinstance(i, int):
                    ok_idx.setdefault((t, i), False)
                    ok_idx[(t, i)] = ok_idx[(t, i)] or live
        pt = phone_tier(tiers)
        phone, off, colors = [], [], []
        for t, tier in enumerate(tiers):
            for i, o in enumerate(tier["options"]):
                buyable = ok_idx.get((t, i), True)   # ไม่มีข้อมูล models = ถือว่าซื้อได้
                if t == pt:
                    (phone if buyable else off).append(o)
                elif pt is None or t != pt:
                    colors.append({"n": o, "img": tier["images"][i], "off": 0 if buyable else 1})
        return {"name": str(d.get("name") or d.get("title") or "")[:120], "phone": phone, "off": off,
                "colors": colors[:40], "tiers": [{"name": t["name"], "n": len(t["options"])} for t in tiers],
                "phone_tier": pt, "checked_at": datetime.now().strftime(FMT)}
    return None


def build_queue(a, opts):
    if a.keys:
        out = []
        for k in a.keys:
            m = KEY_RE.search(k) or re.search(r"/product/(\d+)/(\d+)", k) or re.search(r"i\.(\d+)\.(\d+)", k)
            if m:
                out.append("%s_%s" % (m.group(1), m.group(2)))
            else:
                log("อ่านรหัสสินค้าไม่ได้:", k)
        return out
    prods = (load(PRODUCTS, {}) or {}).get("products") or []
    look = set("%s_%s" % m for m in KEY_RE.findall(TRYON.read_text(encoding="utf-8"))) if TRYON.exists() else set()
    old = (datetime.now() - timedelta(days=a.days)).strftime(FMT)
    q = []
    for p in prods:
        k = str(p.get("key") or "")
        if not KEY_RE.fullmatch(k) or not p.get("is_affiliate"):
            continue
        o = opts.get(k)
        if o and o.get("checked_at", "") >= old and not o.get("error"):
            continue
        named = bool(PHONE_RE.search(str(p.get("name") or "")))
        # ชื่อไม่ระบุรุ่น = เว็บเดาไม่ได้เลย (ไม่ขึ้นหน้ารุ่นไหน) → มาก่อน · ต่อด้วยเคสที่ลองทาบได้ · แล้วขายดี
        q.append(((0 if not named else 1 if k in look else 2), -(p.get("sold") or 0), k))
    q.sort()
    return [x[-1] for x in q]


def main():
    ap = argparse.ArgumentParser(description="ดึงตัวเลือกรุ่น/สีจากหน้าสินค้า Shopee")
    ap.add_argument("keys", nargs="*")
    ap.add_argument("--limit", type=int, default=8, help="จำนวนหน้าสินค้าต่อรอบ (ช้าไว้ก่อน: 5–8)")
    ap.add_argument("--days", type=int, default=14)
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--publish-only", action="store_true", help="สร้าง assets/options.js จากข้อมูลที่มี ไม่เปิด Shopee")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--verify-wait", type=float, default=15, help="รอคนกด verify กี่นาที")
    a = ap.parse_args()
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    opts = load(OUT, {})
    if a.publish_only:
        log("assets/options.js: %d ชิ้น" % write_site_js(opts))
        return 0
    queue = build_queue(a, opts)[: a.limit]
    log("คิวรอบนี้ %d ชิ้น (มีข้อมูลแล้ว %d ชิ้น)" % (len(queue), sum(1 for v in opts.values() if not v.get("error"))))
    for k in queue:
        log("  ", k)
    if a.dry or not queue:
        return 0

    why = guard.why_not(a.force)
    if why:
        log("ไม่เริ่ม:", why)
        return 3
    guard.acquire(WHO)
    cfg = B.load_config(B.BASE_DIR / "config.json")
    cfg["max_page_loads_per_run"] = len(queue) + 2
    B.ensure_chrome(cfg)
    from playwright.sync_api import sync_playwright
    status, got = "ok", 0
    with sync_playwright() as p:
        ctx = B.launch(p, cfg, headless=False)
        b = B.Bot(cfg, ctx, False, {})
        try:
            for k in queue:
                sid, iid = k.split("_")
                url = "https://shopee.co.th/product/%s/%s" % (sid, iid)
                try:
                    b.goto(url)
                except B.Blocked as e:   # ให้คนกดยืนยันเองในหน้าต่าง Chrome ของบอท (บอทไม่กดแทน) แล้วโหลดหน้าเดิมซ้ำ 1 ครั้ง
                    if e.kind != "verify":
                        raise
                    log("เจอหน้ายืนยันตัวตน — กดยืนยันเองในหน้าต่าง Chrome ของบอท (รอสูงสุด %g นาที)" % a.verify_wait)
                    end = time.time() + a.verify_wait * 60
                    while "verify" in b.page.url and time.time() < end:
                        b.page.wait_for_timeout(3000)
                    if "verify" in b.page.url:
                        raise
                    b.goto(url)
                r = None
                for _, data in b.payloads():
                    r = extract(data, iid)
                    if r:
                        break
                b._note_result(bool(r))   # ไม่เจอข้อมูล 2 หน้าติด = น่าจะโดนจำกัด → หยุด
                if r:
                    opts[k] = r
                    got += 1
                    log("%s รุ่น %d (หมด %d) · สี/ลาย %d · %s" % (k, len(r["phone"]), len(r["off"]), len(r["colors"]), r["name"][:40]))
                else:
                    opts[k] = {"error": "no_data", "checked_at": datetime.now().strftime(FMT)}
                    log("%s ไม่เจอข้อมูลตัวเลือก" % k)
                save(opts)
        except B.Blocked as e:
            status = "blocked_" + e.kind
            guard.note_block(WHO, b.loads, e.kind)
            log("!!! โดนบล็อก (%s) หลัง %d หน้า — หยุด ไม่ลองซ้ำ" % (e.kind, b.loads))
        except B.BudgetUsed:
            log("ครบจำนวนหน้าที่ตั้งไว้")
        except KeyboardInterrupt:
            status = "interrupted"
            log("หยุดโดยผู้ใช้ — บันทึกผลที่ได้แล้ว")
        finally:
            try:
                b.page.close() if cfg.get("browser_mode") == "attach" else ctx.close()
            except Exception:
                pass
    n = write_site_js(opts) if got else 0
    log("จบ: %s · ได้ %d/%d ชิ้น · %d หน้า · ไฟล์ %s%s" % (status, got, len(queue), b.loads, OUT.name,
                                                       " · assets/options.js %d ชิ้น" % n if got else ""))
    return 0 if status == "ok" else 2


if __name__ == "__main__":
    sys.exit(main())
